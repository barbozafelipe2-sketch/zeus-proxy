import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {artifactTypesFromText} from '../netlify/functions/_shared/intent.mjs';
import {validateArtifactInput} from '../netlify/functions/_shared/artifact-limits.mjs';
const artifact=readFileSync('netlify/functions/_shared/artifact.mjs','utf8');
const api=readFileSync('netlify/functions/artifacts.mjs','utf8');
const delivered=readFileSync('netlify/functions/_shared/artifact-delivery.mjs','utf8');
const revise=readFileSync('netlify/functions/artifact-revise.mjs','utf8');
const ui=readFileSync('public/app.js','utf8');
assert.deepEqual(artifactTypesFromText('Create a single-page HTML preview'),['html']);
assert.deepEqual(artifactTypesFromText('Create PDF and HTML'),['pdf','html']);
assert.equal(validateArtifactInput('html','<!doctype html><h1>Hello</h1>').normalized,'html');
assert.match(artifact,/normalized === 'html'/);
assert.match(api,/'md','html','zip'/);
assert.match(delivered,/new Set\(\['pdf','docx','xlsx','pptx','csv','html'\]\)/);
assert.match(revise,/parent_artifact_id/);
assert.match(revise,/source\.type!=='html'/);
assert.match(revise,/parent\.project_id,parent\.conversation_id/);
assert.match(revise,/discardStagedArtifact/);
assert.match(ui,/function openHtmlEditor/);
assert.match(ui,/data-edit-html/);
assert.match(ui,/sandbox="allow-scripts"/);
assert.match(ui,/connect-src 'none'/);
assert.match(ui,/form-action 'none'/);
assert.match(ui,/\/api\/artifact-revise/);
console.log('Phase 4 HTML preview, editor, format and revision structural tests PASS');
