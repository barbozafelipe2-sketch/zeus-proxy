import assert from 'node:assert/strict';
import {systemDoctor} from '../netlify/functions/_shared/system-doctor.mjs';
import {runDoctor} from './doctor.mjs';
const fixture={goLive:{database:true},storageMaintenance:{skipped:true},providerReadiness:{openai:{configured:true,status:'configured_unverified'}},queueDiagnostics:{inspected:1,active:1,expired:0},monthlyBudget:{available:true,executionCount:1,unpricedExecutionCount:1}};
const check=(h,id)=>systemDoctor(h).checks.find(c=>c.id===id).status;
assert.equal(check(fixture,'providers'),'unverified');
assert.equal(check(fixture,'storage'),'unknown');
assert.equal(check(fixture,'costs'),'partial');
assert.equal(check({},'database'),'unknown');
assert.equal(check({},'queue'),'unknown');
assert.equal(check({...fixture,queueDiagnostics:{inspected:1,active:0,expired:1}},'queue'),'failed');
assert.equal(systemDoctor({...fixture,queueDiagnostics:{expired:1}}).status,'blocked');
assert.equal(check({...fixture,warnings:[{section:'providerReadiness'}]},'providers'),'unknown');
assert.equal(check({...fixture,providerReadiness:{a:{configured:true,status:'observed_healthy'}}},'providers'),'observed');
assert.equal(check(fixture,'deployment'),'unverified');
let calls=[];const doctor=systemDoctor(fixture,'2026-11-12T00:00:00Z');
const fetcher=async(url,options)=>{calls.push({url:String(url),options});return Response.json({doctor});};
assert.equal(await runDoctor({base:'https://example.test',fetcher,log:()=>{}}),0);
assert.equal(calls.length,1);assert.equal(calls[0].url,'https://example.test/api/health');assert.equal(calls[0].options.redirect,'error');
await assert.rejects(runDoctor({base:'https://user:secret@example.test',fetcher}));
await assert.rejects(runDoctor({base:'https://example.test',fetcher:async()=>new Response('<html>login secret</html>',{headers:{'content-type':'text/html'}})}),/Doctor unavailable/);
await assert.rejects(runDoctor({base:'https://example.test',fetcher:async()=>Response.json({})}),/missing/);
assert.equal(doctor.providerRequests,0);
console.log('system doctor tests: PASS');
